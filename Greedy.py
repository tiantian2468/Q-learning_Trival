# 权重系数
w_recommend = 0.5  # 推荐度权重
w_time = 0.3       # 游览时长权重
w_commute = 0.2    # 通勤时间权重

# 计算适应度函数
def calculate_fitness(recommendation, time, commute):
    return w_recommend * recommendation - w_time * time - w_commute * commute
def calculate_reward(recommendation, time, commute):
    return recommendation - time - commute

# 贪婪算法
def greedy_algorithm(spot_info, commute_time, max_time):
    selected_spots = []
    total_time = 0
    total_fitness = 0
    rewards = []  # 用来存储每个 episode 的总奖励
    # 假设我们有多个回合（例如10个回合）
    for episode in range(1000):  # 10个回合
        episode_fitness = 0
        reward=0
        while True:
            best_fitness = -float('inf')
            best_spot = None
            # 遍历所有景点，选择适应度最高的
            rew =0
            for i, (recommendation, time, cost) in enumerate(spot_info):
                if i not in selected_spots:  # 避免重复选择
                    # 计算适应度函数
                    fitness = calculate_fitness(recommendation, time, commute_time[i][0])  # 假设选择第一个景点的通勤时间
                    # rew = calculate_reward(recommendation, time, commute_time[i][0])
                    if fitness > best_fitness and total_time + time <= max_time:
                        best_fitness = fitness
                        best_spot = i
                        rew = calculate_reward(recommendation, time, commute_time[i][0])
            if best_spot is None:
                break  # 如果没有可选择的景点，则退出
            # 选择该景点
            selected_spots.append(best_spot)
            total_time += spot_info[best_spot][1]
            episode_fitness += best_fitness
            reward += rew
            # rewards.append(reward)


        rewards.append(reward)  # 保存每个回合的奖励

    return selected_spots, total_time, rewards

# 执行贪婪算法
max_time = 10
selected_spots, total_time, rewards = greedy_algorithm(spot_info, commute_time, max_time)

